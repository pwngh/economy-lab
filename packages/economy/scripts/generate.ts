import {
  chmodSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../../..', import.meta.url));
const PACKAGES = join(ROOT, 'packages');
const UMBRELLA = join(PACKAGES, 'economy');
const SRC = join(UMBRELLA, 'src');

const GENERATED =
  '// This file is generated by packages/economy/scripts/generate.ts — do not edit.\n';

/** One entry of a package's `exports` map, in either spelling npm accepts. */
type ExportEntry =
  | string
  | { readonly types?: string; readonly default?: string };

/** The fields this generator reads out of a sibling, and the ones it writes into its own. */
interface PackageJson {
  name: string;
  version: string;
  exports?: Record<string, ExportEntry>;
  dependencies?: Record<string, string>;
  peerDependencies?: Record<string, string>;
  peerDependenciesMeta?: Record<string, { optional: boolean }>;
  publishConfig?: { access: string };
  bin?: Record<string, string>;
}

interface WorkspacePackage {
  readonly dir: string;
  readonly json: PackageJson;
}

const readJson = <T>(path: string): T =>
  JSON.parse(readFileSync(path, 'utf8')) as T;

/** The stub's path mirrors the target specifier, so a door and its sub-doors nest naturally. */
const sourceFileFor = (specifier: string): string =>
  `${specifier.replace('@pwngh/economy-', '')}.ts`;
const packageOf = (specifier: string): string =>
  specifier.split('/').slice(0, 2).join('/');

/** Every workspace package, by npm name. */
function workspacePackages(): Map<string, WorkspacePackage> {
  const out = new Map<string, WorkspacePackage>();
  for (const entry of readdirSync(PACKAGES, { withFileTypes: true })) {
    const manifest = join(PACKAGES, entry.name, 'package.json');
    if (entry.isDirectory() && existsSync(manifest)) {
      out.set(readJson<PackageJson>(manifest).name, {
        dir: join(PACKAGES, entry.name),
        json: readJson<PackageJson>(manifest),
      });
    }
  }
  return out;
}

/** The export key a specifier names, in the spelling a package's own exports map uses. */
const subpathOf = (specifier: string): string =>
  specifier.slice(packageOf(specifier).length).replace(/^\//, '.$&') || '.';

/**
 * The source behind one export, taken from the package's own map so a subpath is read at
 * wherever it actually lives rather than wherever its name suggests.
 */
function sourceOf(pkg: WorkspacePackage, sub: string): string | undefined {
  const entry = (pkg.json.exports ?? {})[sub];
  const target =
    typeof entry === 'string' ? entry : (entry?.types ?? entry?.default);
  const stems: string[] = [];
  if (typeof target === 'string')
    stems.push(target.replace(/^\.\/dist\//, '').replace(/\.d\.ts$|\.js$/, ''));
  stems.push(sub === '.' ? 'index' : sub.replace(/^\.\//, ''));
  return stems
    .flatMap((s) => [`src/${s}.ts`, `src/${s}.tsx`])
    .map((c) => join(pkg.dir, c))
    .find(existsSync);
}

/**
 * Whether a target exports values or only types. A `export *` from a types-only module is
 * a runtime no-op that still costs a resolution, so those doors say `export type *`.
 */
function exportMode(pkg: WorkspacePackage, sub: string): 'value' | 'type' {
  const path = sourceOf(pkg, sub);
  // Anything but a type or an interface is read as a value. The wrong guess in that
  // direction wastes a resolution; the other way silently drops a runtime binding.
  if (!path) return 'value';
  const exported = readFileSync(path, 'utf8').match(/^export\s+\S+/gm) ?? [];
  return exported.some((e) => !/^export\s+(type|interface)\b/.test(e))
    ? 'value'
    : 'type';
}

/**
 * Every door checked and every sibling peer gathered, before a single file is written — so a
 * manifest this refuses leaves the umbrella exactly as it found it.
 */
function validate(
  doors: readonly (readonly [string, string])[],
  packages: Map<string, WorkspacePackage>,
) {
  const problems: string[] = [];
  const peerDependencies: Record<string, string> = {};
  const peerDependenciesMeta: Record<string, { optional: boolean }> = {};
  for (const [key, specifier] of doors) {
    if (!key.startsWith('economy/')) {
      problems.push(`door "${key}" must be spelled economy/…`);
      continue;
    }
    const pkg = packages.get(packageOf(specifier));
    if (!pkg) {
      problems.push(
        `door "${key}" names ${packageOf(specifier)}, which is not a workspace package`,
      );
      continue;
    }
    const sub = subpathOf(specifier);
    if (!Object.keys(pkg.json.exports ?? {}).includes(sub))
      problems.push(
        `door "${key}" points at ${specifier}, which ${pkg.json.name} does not export`,
      );

    // Two siblings disagreeing is one more refusal rather than a stop halfway through writing.
    for (const [peer, range] of Object.entries(
      pkg.json.peerDependencies ?? {},
    )) {
      if (peerDependencies[peer] && peerDependencies[peer] !== range) {
        problems.push(
          `peer conflict on ${peer}: ${peerDependencies[peer]} vs ${range}`,
        );
        continue;
      }
      // Always optional here, whatever the sibling says: no consumer opens every door, so a
      // required peer would install React for a project that only reads economy/ops.
      peerDependencies[peer] = range;
      peerDependenciesMeta[peer] = { optional: true };
    }
  }
  return { problems, peerDependencies, peerDependenciesMeta };
}

function main(): void {
  const manifest = readJson<Record<string, string>>(
    join(UMBRELLA, 'manifest.json'),
  );
  const doors = Object.entries(manifest).filter(
    ([key]) => !key.startsWith('_'),
  );
  const packages = workspacePackages();
  const { problems, peerDependencies, peerDependenciesMeta } = validate(
    doors,
    packages,
  );
  if (problems.length) {
    for (const problem of problems) console.error(problem);
    process.exitCode = 1;
    return;
  }

  const before = Object.keys(
    readJson<PackageJson>(join(UMBRELLA, 'package.json')).exports ?? {},
  );
  rmSync(SRC, { recursive: true, force: true });
  mkdirSync(SRC, { recursive: true });

  const exportsMap: Record<string, ExportEntry> = {};
  const dependencies: Record<string, string> = {};

  for (const [key, specifier] of doors) {
    // Every door was resolved against the workspace by validate() above, which stops the run.
    const pkg = packages.get(packageOf(specifier))!;
    const file = sourceFileFor(specifier);
    const mode = exportMode(pkg, subpathOf(specifier));
    mkdirSync(dirname(join(SRC, file)), { recursive: true });
    writeFileSync(
      join(SRC, file),
      `${GENERATED}export ${mode === 'type' ? 'type ' : ''}* from '${specifier}';\n`,
    );

    const stem = file.replace(/\.ts$/, '');
    exportsMap[`./${key.replace('economy/', '')}`] = {
      types: `./dist/${stem}.d.ts`,
      default: `./dist/${stem}.js`,
    };
    // Read the sibling's real version — a hardcoded range silently ships a wrong dependency
    // the first time any package bumps out of step with the umbrella.
    dependencies[packageOf(specifier)] = `^${pkg.json.version}`;
  }

  // The bin is the one hand-shaped file, and it imports a generated door like any consumer.
  writeFileSync(
    join(SRC, 'cli-entry.ts'),
    `#!/usr/bin/env node\n${GENERATED}` +
      "import * as process from 'node:process';\n\n" +
      "import { runEconomy } from './cli.js';\n\n" +
      'try {\n  const exitCode = await runEconomy(process.argv.slice(2));\n' +
      '  process.exit(exitCode);\n} catch (error) {\n  console.error(error);\n' +
      '  process.exit(1);\n}\n',
  );
  chmodSync(join(SRC, 'cli-entry.ts'), 0o755);

  const pkgPath = join(UMBRELLA, 'package.json');
  const pkg = readJson<PackageJson>(pkgPath);
  exportsMap['./package.json'] = './package.json';
  pkg.exports = exportsMap;
  // No publishConfig.exports: `exports` already points at dist, and a second copy silently
  // replaces the first at publish time, so a subpath added to one and not the other vanishes.
  pkg.publishConfig = { access: 'public' };
  pkg.dependencies = dependencies;
  // Written or deleted every run. A peer kept after the last sibling dropped it is one the
  // umbrella goes on declaring with nothing behind it.
  if (Object.keys(peerDependencies).length) {
    pkg.peerDependencies = peerDependencies;
    pkg.peerDependenciesMeta = peerDependenciesMeta;
  } else {
    delete pkg.peerDependencies;
    delete pkg.peerDependenciesMeta;
  }
  pkg.bin = { economy: './dist/cli-entry.js' };
  writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`);

  // Adding a door is additive; removing one breaks a consumer's import.
  const after = Object.keys(exportsMap);
  const added = after.filter((k) => !before.includes(k));
  const removed = before.filter((k) => !after.includes(k));
  process.stdout.write(
    `generate: ${doors.length} doors, ${Object.keys(dependencies).length} packages\n`,
  );
  if (added.length) process.stdout.write(`  added:   ${added.join(' ')}\n`);
  if (removed.length)
    process.stdout.write(
      `  REMOVED: ${removed.join(' ')} — breaking, bump major\n`,
    );
}

main();
